"""Build the fixed scenario list and the tuning / held-out split (PRD R3, P3 spec section 4). Run once, in the
container, then commit eval/scenarios.csv and config/scenario_filter/{tuning,heldout}.yaml before any planner run.

    docker/run.sh python eval/make_scenario_list.py
"""
import csv
import os
from pathlib import Path

import yaml

import nuplan
from nuplan.planning.scenario_builder.nuplan_db.nuplan_scenario_builder import NuPlanScenarioBuilder
from nuplan.planning.scenario_builder.nuplan_db.nuplan_scenario_utils import ScenarioMapping
from nuplan.planning.scenario_builder.scenario_filter import ScenarioFilter
from nuplan.planning.utils.multithreading.worker_sequential import Sequential

PER_TYPE = 20
REPO = Path(__file__).resolve().parents[1]
DEVKIT_CFG = Path(nuplan.__file__).parent / "planning/script/config/common"


def _yaml(path: Path) -> dict:
    return yaml.safe_load(path.read_text())


def main() -> None:
    challenge = _yaml(DEVKIT_CFG / "scenario_filter/nuplan_challenge_scenarios.yaml")
    mapping = _yaml(DEVKIT_CFG / "scenario_builder/scenario_mapping/nuplan_scenario_mapping.yaml")
    root = os.environ["NUPLAN_DATA_ROOT"]
    builder = NuPlanScenarioBuilder(
        data_root=f"{root}/nuplan-v1.1/splits/mini",
        map_root=os.environ["NUPLAN_MAPS_ROOT"],
        sensor_root=f"{root}/nuplan-v1.1/sensor_blobs",
        db_files=None,
        map_version="nuplan-maps-v1.0",
        scenario_mapping=ScenarioMapping(mapping["scenario_map"], mapping["subsample_ratio_override"]),
        verbose=False,
    )
    # The same filter the simulations will use, minus the token list: challenge types, expand off, invalid goals off.
    fields = {k: v for k, v in challenge.items() if not k.startswith("_")}
    scenarios = builder.get_scenarios(ScenarioFilter(**fields), Sequential())

    by_type = {}
    for s in scenarios:
        by_type.setdefault(s.scenario_type, []).append(s)
    kept = []
    for t in sorted(by_type):
        kept += sorted(by_type[t], key=lambda s: s.token)[:PER_TYPE]
    kept.sort(key=lambda s: s.token)
    assert len({s.token for s in kept}) == len(kept), "a token appears under two types"

    rows = [
        {"token": s.token, "scenario_type": s.scenario_type, "log_name": s.log_name, "map": s.map_api.map_name,
         "split": "tuning" if i % 3 == 0 else "heldout"}
        for i, s in enumerate(kept)
    ]
    with open(REPO / "eval/scenarios.csv", "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)

    # Filter YAMLs: the challenge filter with this split's tokens and logs. Listing the logs skips the other .db files.
    for split in ("tuning", "heldout"):
        mine = [r for r in rows if r["split"] == split]
        cfg = dict(challenge, scenario_tokens=[r["token"] for r in mine],
                   log_names=sorted({r["log_name"] for r in mine}))
        out = REPO / f"config/scenario_filter/{split}.yaml"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(f"# Generated by eval/make_scenario_list.py; do not edit. {len(mine)} scenarios.\n"
                       + yaml.safe_dump(cfg, sort_keys=False))

    counts = {t: (sum(r["scenario_type"] == t and r["split"] == "tuning" for r in rows),
                  sum(r["scenario_type"] == t for r in rows)) for t in sorted(by_type)}
    print(f"{len(rows)} scenarios, {sum(r['split'] == 'tuning' for r in rows)} tuning")
    for t, (tun, tot) in counts.items():
        print(f"  {t:58s} {tot:3d} total, {tun:3d} tuning, {len(by_type[t]):6d} available")


if __name__ == "__main__":
    main()
